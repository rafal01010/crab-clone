import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

const catalogue = JSON.parse(
  await readFile(
    new URL('../docs/content/source-catalogue.json', import.meta.url),
    'utf8',
  ),
);
function requirement(value) {
  switch (value.kind) {
    case 'none':
    case 'unresolved':
      return { kind: 'none' };
    case 'content':
      return { kind: 'rank', id: value.id, minimum: value.minRank ?? 1 };
    case 'specialization':
      return { kind: 'specialization', id: value.id };
    case 'allOf':
    case 'anyOf':
      return {
        kind: value.kind === 'allOf' ? 'all' : 'any',
        conditions: value.conditions.map(requirement),
      };
    default:
      throw new Error(`Unsupported prerequisite kind: ${value.kind}`);
  }
}
const records = catalogue.records.map((record) => {
  const maximum = record.candidateFields.maxRank;
  const maxRank =
    maximum === 'Infinite'
      ? Number.MAX_SAFE_INTEGER
      : maximum == null || maximum === 'None'
        ? 1
        : Number(maximum);
  if (!Number.isSafeInteger(maxRank) || maxRank < 1)
    throw new Error(`Invalid rank for ${record.id}`);
  const rankExclusions = record.availability.rankConstraints.map((item) => {
    const match = /\bLv\s*(\d+)\b/i.exec(item.raw);
    if (!match) throw new Error(`Unrecognized rank exclusion for ${record.id}`);
    return { id: item.other, minimum: Number(match[1]) };
  });
  const specializationChoices = record.specializations.map((choice) => ({
    id: choice.id,
    name: choice.sourceName,
    triggerRank:
      choice.triggerRank.kind === 'reported'
        ? choice.triggerRank.value
        : Math.min(3, maxRank),
    carcinisationBonus: 0,
  }));
  return {
    id: record.id,
    aliases: [],
    disposition: 'blocked',
    selectable: false,
    name: record.sourceName,
    description: 'Unavailable.',
    pool: record.availability.pool,
    maxRank,
    rarities: [],
    values: {},
    requirement: requirement(record.availability.prerequisites),
    exclusions: record.availability.exclusions,
    ...(rankExclusions.length ? { rankExclusions } : {}),
    affinities: [],
    effect: 'unimplemented',
    specializations: specializationChoices.map((choice) => choice.id),
    ...(specializationChoices.length ? { specializationChoices } : {}),
  };
});
const source = `// Generated by scripts/generate-research-graph.mjs from the research catalogue.\nimport type { ContentDefinition } from './registry.js';\nexport const researchGraph = ${JSON.stringify(records)} satisfies readonly ContentDefinition[];\n`;
await writeFile(
  new URL('../server/content/research-graph.ts', import.meta.url),
  await format(source, {
    parser: 'typescript',
    singleQuote: true,
    trailingComma: 'all',
  }),
);
